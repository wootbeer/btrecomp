#!/usr/bin/env python3
# Writes BattleTanxSyms/battletanx.us.rev0.syms.toml from the function list
# (tools/find_functions.py) and the library names (syms/library_names.txt).
# Usage: python3 tools/make_syms.py <functions.json>
import json, sys

funcs = json.load(open(sys.argv[1]))
names = {}
for line in open('syms/library_names.txt'):
    line = line.split('#')[0].strip()
    if line:
        a, n = line.split()
        names[int(a, 16)] = n

lines = []
for f in funcs:
    v = f['vram']
    n = names.get(v, f'func_{v:08X}')
    lines.append(f'    {{ name = "{n}", vram = 0x{v:08X}, size = 0x{f["size"]:X} }},')

open('BattleTanxSyms/battletanx.us.rev0.syms.toml', 'w').write(f'''# Symbol file for BattleTanx (USA) 1.0, for N64Recomp.
#
# Generated by tools/find_functions.py (function boundaries by control-flow
# traversal) and tools/make_syms.py (library names from syms/library_names.txt).
# Regenerate rather than editing by hand; see BattleTanxSyms/README.md.
#
# One section: the code and data the boot code loads from ROM 0x1000 to
# 0x80071000. Code runs to 0x80125550, data to 0x80147040, then BSS
# (cleared by the entry point, func_80071000).

[[section]]
name = ".main"
rom = 0x00001000
vram = 0x80071000
size = 0xD6040

functions = [
{chr(10).join(lines)}
]
''')
print(len(lines), 'functions,', sum(1 for f in funcs if f['vram'] in names), 'named')
